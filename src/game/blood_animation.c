#ifndef TARGET_N64
/**
 * Paces both blood animations (death bleed-out and gunbarrel intro) at 30fps.
 *
 * Both callers advance from a display list builder that runs once per rendered
 * frame, so counting calls only gives 30fps at exactly 60fps. This paces on
 * real time instead: 775875 counts is the port's 60Hz field length
 * (frametiming.c), so two of them is 30fps at any frame rate. It avoids
 * g_ClockTimer / g_GlobalTickCount because they stop with the mission clock and
 * would strand a half-drawn screen of blood.
 *
 * Unsigned arithmetic keeps the difference correct across osGetCount wraparound
 * (about every 92 seconds). A stamp of 0 means "not started", so the first
 * frame of a sequence shows immediately.
 */
s32 portBloodFrameDue(u32 *stamp)
{
    extern s32 portPaceDue(u32 *stamp, u32 counts); /* frametiming.c */
    extern int portCoopNetDriven(void);
    extern unsigned int portCoopNetTick(void);

    /* netplay: wall-clock pacing would make the blood animation (and with it the dead Bond's gun and death states, which are
     * in the state hash) depend on this machine's speed. Every second sim tick instead: 30 fps of the 60 Hz sim. */
    if (portCoopNetDriven())
    {
        return (portCoopNetTick() & 1u) == 0;
    }
    return portPaceDue(stamp, BLOOD_FRAME_COUNTS);
}
#endif

s32 die_blood_image_routine(s32 arg0) {
   s8 sp37;
   u8* temp_v0_2;

   if (arg0 == 0) {
      g_CurrentPlayer->bloodImgCur = die_blood_image_1;
   } else if (arg0 == 1) {
      if (g_CurrentPlayer->bloodImgNxt < &die_blood_image_end) {
         g_CurrentPlayer->bloodImgCur = g_CurrentPlayer->bloodImgNxt;
      }
   }

   g_CurrentPlayer->bloodImgIdx = (1 - g_CurrentPlayer->bloodImgIdx);
   g_CurrentPlayer->bloodImgBufPtrArray[g_CurrentPlayer->bloodImgIdx] = dynAllocate(BLOOD_IMG_WIDTH * BLOOD_IMG_HEIGHT);
   temp_v0_2 = dynAllocate(BLOOD_IMG_WIDTH * BLOOD_IMG_HEIGHT);
   g_CurrentPlayer->bloodImgNxt = decrypt_bleeding_animation_data(g_CurrentPlayer->bloodImgCur, BLOOD_IMG_WIDTH, BLOOD_IMG_HEIGHT, temp_v0_2, &sp37);
   bloodImgTranspose(temp_v0_2, BLOOD_IMG_WIDTH, BLOOD_IMG_HEIGHT, g_CurrentPlayer->bloodImgBufPtrArray[g_CurrentPlayer->bloodImgIdx]);
   sub_GAME_7F01D02C(g_CurrentPlayer->bloodImgBufPtrArray[g_CurrentPlayer->bloodImgIdx], BLOOD_IMG_WIDTH, g_CurrentPlayer->bloodImgBufPtrArray[g_CurrentPlayer->bloodImgIdx]);
   sub_GAME_7F01CEEC(g_CurrentPlayer->bloodImgBufPtrArray[g_CurrentPlayer->bloodImgIdx], BLOOD_IMG_WIDTH, g_CurrentPlayer->bloodImgBufPtrArray[g_CurrentPlayer->bloodImgIdx]);
   sub_GAME_7F01CC94(g_CurrentPlayer->bloodImgBufPtrArray[g_CurrentPlayer->bloodImgIdx], BLOOD_IMG_WIDTH * BLOOD_IMG_HEIGHT, g_CurrentPlayer->bloodImgBufPtrArray[g_CurrentPlayer->bloodImgIdx]);

#ifndef TARGET_N64
   { /* PORT: the frames are CPU-generated into two flip-flop buffers, and
      * fast3d's texture cache keys on the address. Evict the stale entry so
      * each new frame's texels upload instead of reusing frame 0. */
      extern void gfx_texture_cache_delete(const u8 *orig_addr);
      gfx_texture_cache_delete(g_CurrentPlayer->bloodImgBufPtrArray[g_CurrentPlayer->bloodImgIdx]);
   }
#endif

   return (g_CurrentPlayer->bloodImgNxt >= &die_blood_image_end);
}


